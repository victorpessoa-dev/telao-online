create or replace function public.handle_new_user () returns trigger language plpgsql security definer
set
  search_path = public as $$
begin
  insert into public.profiles(id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', new.email))
  on conflict (id) do update set display_name = coalesce(excluded.display_name, profiles.display_name);
  return new;
end $$;

create trigger on_auth_user_created
after insert on auth.users for each row
execute function public.handle_new_user ();

create or replace function public.owns_church (target_church_id uuid) returns boolean language sql stable security definer
set
  search_path = public as $$
  select exists (select 1 from public.churches where id = target_church_id and admin_id = auth.uid())
$$;

create or replace function public.is_admin () returns boolean language sql stable security definer
set
  search_path = public as $$
  -- A newly invited administrator can enter the setup flow before a church
  -- exists. The ownership fallback keeps already-provisioned accounts valid.
  select coalesce(auth.jwt()->'app_metadata'->>'role', '') = 'admin'
    or exists (select 1 from public.churches where admin_id = auth.uid())
$$;

create or replace function public.is_public_church (target_church_id uuid) returns boolean language sql stable security definer
set
  search_path = public as $$
  select exists (select 1 from public.churches where id = target_church_id and is_active)
$$;

create or replace function public.owns_media_object (object_name text) returns boolean language plpgsql stable security definer
set
  search_path = public,
  storage as $$
declare church_folder uuid;
begin
  church_folder := (storage.foldername(object_name))[1]::uuid;
  return public.owns_church(church_folder);
exception when invalid_text_representation then return false;
end $$;

