create or replace function public.log_sponsor_impressions (logs_arg jsonb) returns integer language plpgsql security definer
set search_path = public as $$
declare count_processed integer := 0;
begin
  if logs_arg is null or jsonb_typeof(logs_arg) <> 'array' then raise exception 'logs_arg must be a JSON array'; end if;
  with logs as (
    select coalesce((item->>'event_id')::uuid, gen_random_uuid()) as event_id,
      (item->>'sponsor_id')::uuid as sponsor_id,
      coalesce((item->>'displayed_at')::timestamptz,now()) as displayed_at,
      -- Aggregated offline batches may represent more than one rotation.
      least(greatest(coalesce((item->>'duration_seconds')::integer,0),0),86400) as duration_seconds,
      least(greatest(coalesce((item->>'views_count')::integer,1),1),10000) as views_count,
      coalesce(nullif(item->>'source',''),'telao') as source
    from jsonb_array_elements(logs_arg) item
  ), eligible as (
    select l.* from logs l
    join public.sponsors s on s.id=l.sponsor_id and s.active
    join public.churches c on c.id=s.church_id and c.is_active
  ), inserted as (
    insert into public.sponsor_impressions(event_id,sponsor_id,displayed_at,duration_seconds,views_count,source)
    select event_id,sponsor_id,displayed_at,duration_seconds,views_count,source from eligible
    on conflict (event_id) do nothing
    returning sponsor_id,displayed_at,duration_seconds,views_count
  ), totals as (
    select sponsor_id,sum(views_count)::integer as views,sum(duration_seconds)::integer as total_seconds,max(displayed_at) as last_displayed_at
    from inserted group by sponsor_id
  ), updated as (
    update public.sponsors s
    set views=s.views+t.views,total_seconds=s.total_seconds+t.total_seconds,
      last_displayed_at=greatest(coalesce(s.last_displayed_at,'-infinity'::timestamptz),t.last_displayed_at)
    from totals t where s.id=t.sponsor_id returning s.id
  ), rollups as (
    insert into public.sponsor_impression_daily_rollups(
      sponsor_id,displayed_on,views,total_seconds,last_displayed_at
    )
    select sponsor_id,displayed_at::date,sum(views_count)::integer,sum(duration_seconds)::integer,max(displayed_at)
    from inserted group by sponsor_id,displayed_at::date
    on conflict (sponsor_id,displayed_on) do update set
      views = public.sponsor_impression_daily_rollups.views + excluded.views,
      total_seconds = public.sponsor_impression_daily_rollups.total_seconds + excluded.total_seconds,
      last_displayed_at = greatest(
        coalesce(public.sponsor_impression_daily_rollups.last_displayed_at, '-infinity'::timestamptz),
        excluded.last_displayed_at
      )
    returning sponsor_id
  ) select count(*) into count_processed from inserted;
  return count_processed;
end $$;

-- Global playlist shared by every public display and the short-lived token
-- that identifies the one official display allowed to submit metrics.
create table public.telao_schedules (
  church_id uuid primary key references public.churches(id) on delete cascade,
  version bigint not null default 1,
  seed text not null,
