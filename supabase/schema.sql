create or replace function public.get_public_churches () returns table (
  id uuid,
  name text,
  slug text,
  city text,
  logo_url text,
  cover_url text
) language sql stable security definer
set
  search_path = public as $$
  select c.id,c.name,c.slug,c.city,c.logo_url,c.cover_url from public.churches c where c.is_active order by c.name
$$;

