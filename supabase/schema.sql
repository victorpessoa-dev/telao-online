-- vPlayCast - consolidated schema for a new Supabase project.
-- Model: one administrator per church; all application content belongs to a
-- church and DELETE is permanent (no soft-delete/audit actor columns).
create extension if not exists pgcrypto;

do $$ begin
  create type public.sponsor_kind as enum ('NORMAL', 'MASTER');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.media_type as enum ('image', 'video');
exception when duplicate_object then null; end $$;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete restrict,
  display_name text,
  created_at timestamptz not null default now()
);

create table public.churches (
  id uuid primary key default gen_random_uuid(),
  -- Administrators are granted through auth.app_metadata.role = 'admin'
  -- when invited. Ownership keeps every church's content isolated.
  admin_id uuid not null unique references auth.users (id) on delete restrict,
  name text not null check (length(trim(name)) > 0),
  -- Generated by the application but editable by the administrator.
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  -- The three required church fields are name, slug and city.
  city text not null check (length(trim(city)) > 0),
  logo_url text,
  cover_url text,
  social_links jsonb not null default '[]'::jsonb,
  sponsorship_guidelines text not null default '',
  settings jsonb not null default '{}'::jsonb,
  public_views integer not null default 0 check (public_views >= 0),
  content_version bigint not null default 1,
  -- Controls visibility on the landing page and every /{slug}/... public URL.
  is_active boolean not null default true,
  setup_completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.sponsors (
  id uuid primary key default gen_random_uuid(),
  church_id uuid not null references public.churches (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  kind public.sponsor_kind not null default 'NORMAL',
  media_url text,
  media_type public.media_type not null default 'image',
  image_url text,
  website_url text,
  duration_seconds integer not null default 10 check (duration_seconds > 0),
  active boolean not null default true,
  views integer not null default 0 check (views >= 0),
  total_seconds integer not null default 0 check (total_seconds >= 0),
  last_displayed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    length(trim(coalesce(media_url, image_url, ''))) > 0
  )
);

create table public.app_settings (
  church_id uuid not null references public.churches (id) on delete cascade,
  key text not null check (length(trim(key)) > 0),
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (church_id, key)
);

create table public.sponsor_impressions (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null default gen_random_uuid(),
  sponsor_id uuid not null references public.sponsors (id) on delete cascade,
  displayed_at timestamptz not null default now(),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  views_count integer not null default 1 check (views_count > 0),
  source text not null default 'telao' check (length(trim(source)) > 0),
  created_at timestamptz not null default now()
);

-- The raw log remains available for audit, while report screens read the
-- compact daily rollup below instead of scanning every individual display.
create table public.sponsor_impression_daily_rollups (
  sponsor_id uuid not null references public.sponsors (id) on delete cascade,
  displayed_on date not null,
  views integer not null default 0 check (views >= 0),
  total_seconds integer not null default 0 check (total_seconds >= 0),
  last_displayed_at timestamptz,
  primary key (sponsor_id, displayed_on)
);

create index sponsors_church_active_idx on public.sponsors (church_id, active);

-- Covers the hot public telão read path. The HTTP endpoint adds browser/CDN
-- caching; this index keeps the occasional cache miss inexpensive.
create index sponsors_public_telao_idx on public.sponsors (church_id, kind desc, created_at desc)
  include (id, name, media_url, media_type, image_url, website_url, duration_seconds)
  where active;

create index sponsor_impressions_sponsor_displayed_idx on public.sponsor_impressions (sponsor_id, displayed_at desc);
create unique index sponsor_impressions_event_id_key on public.sponsor_impressions (event_id);
create index sponsor_impression_daily_rollups_sponsor_day_idx on public.sponsor_impression_daily_rollups (sponsor_id, displayed_on desc);

create or replace function public.owns_church (target_church_id uuid) returns boolean language sql stable security definer
set
  search_path = public as $$
  select exists (select 1 from public.churches where id = target_church_id and admin_id = auth.uid())
$$;

-- Administrative sponsor mutations are exposed as RPCs so the API contract
-- remains explicit while ownership is checked again inside the database.
create or replace function public.create_admin_sponsor (
  name_arg text,
  kind_arg public.sponsor_kind,
  media_url_arg text,
  media_type_arg public.media_type,
  website_url_arg text,
  duration_seconds_arg integer,
  active_arg boolean,
  church_id_arg uuid
) returns setof public.sponsors
language plpgsql security definer
set search_path = public as $$
begin
  if not public.owns_church(church_id_arg) then
    raise exception 'Você não tem permissão para criar patrocínios nesta igreja'
      using errcode = '42501';
  end if;

  return query
  insert into public.sponsors (
    church_id, name, kind, media_url, media_type, website_url,
    duration_seconds, active
  ) values (
    church_id_arg,
    trim(name_arg),
    kind_arg,
    nullif(trim(media_url_arg), ''),
    media_type_arg,
    nullif(trim(website_url_arg), ''),
    greatest(coalesce(duration_seconds_arg, 10), 1),
    coalesce(active_arg, true)
  ) returning *;
end $$;

create or replace function public.update_admin_sponsor (
  sponsor_id_arg uuid,
  name_arg text,
  kind_arg public.sponsor_kind,
  media_url_arg text,
  media_type_arg public.media_type,
  website_url_arg text,
  duration_seconds_arg integer,
  active_arg boolean
) returns setof public.sponsors
language plpgsql security definer
set search_path = public as $$
begin
  return query
  update public.sponsors as s
  set
    name = trim(name_arg),
    kind = kind_arg,
    media_url = nullif(trim(media_url_arg), ''),
    media_type = media_type_arg,
    website_url = nullif(trim(website_url_arg), ''),
    duration_seconds = greatest(coalesce(duration_seconds_arg, 10), 1),
    active = coalesce(active_arg, true)
  where s.id = sponsor_id_arg
    and public.owns_church(s.church_id)
  returning s.*;

  if not found then
    raise exception 'Patrocínio não encontrado ou sem permissão para alteração'
      using errcode = '42501';
  end if;
end $$;

